import { chromium } from "@playwright/test";
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("http://localhost:5199/score");
await p.waitForTimeout(2500);
const fr = p.getByRole("dialog", { name: "Set up Headpin" });
await fr.getByRole("button", { name: "Start fresh" }).click();
await fr.getByRole("button", { name: "right-handed" }).click();
await p.waitForTimeout(1000);
await p.evaluate(async () => {
  const { db } = await import("/src/db/bowlingDb.ts");
  const sid = await db.sessions.add({ date: "2026-10-19", alley_name: "Chinese Swimming Club", description: "Practice" });
  await db.games.add({ session_id: sid, game_number: 1, final_score: 184, lanes: ["9","10"] });
});
await p.reload(); await p.waitForTimeout(2000);
await p.getByRole("button", { name: "History" }).last().click(); await p.waitForTimeout(1000);
await p.getByRole("button", { name: /Chinese Swimming Club/ }).click(); await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Session stats" }).click(); await p.waitForTimeout(1500);
await p.screenshot({ path: process.argv[2] + "/gap.png", clip: { x: 0, y: 0, width: 390, height: 300 } });
await b.close();
